static void UpdatePokegearBezel(BOOL isPokegear) {
    SIM_WideStamp stamps[2];
    memset(stamps, 0, sizeof(stamps));
    int count = 0;
    if (isPokegear) {
        stamps[0].x = -POKEGEAR_BEZEL_WIDTH;
        stamps[0].height = POKEGEAR_BEZEL_HEIGHT;
        stamps[1].x = 256;
        stamps[1].height = POKEGEAR_BEZEL_HEIGHT;
        stamps[1].flipX = 1;
        count = 2;
    }
    SIM_SetWidescreenStampImage(sPokegearBezelImage, POKEGEAR_BEZEL_WIDTH, 64);
    SIM_SetWidescreenStamps(0, stamps, count); // GF_BG_LYR_MAIN_0
}

void Widescreen_Update(void) {
    FieldSystem *fieldSystem = ShownFieldSystem();
    u8 objWrap = 0;
    u8 wideBgs = 0;
    u8 edgeBgs = 0;
    u8 edgeMirrorBgs = 0;
    BOOL isPokegear = FALSE;
    // A battle in Black 2 and White 2's engine: its arena is 3D, its camera widened as the field camera is
    // (gen5_battle.c); its text box (BG1), the ability bar and the full-screen moves' backgrounds reach the edges, their
    // patterns mirrored, and the party balls' bar (sprites of priority 0) too
    BOOL wide = Gen5BattleShown();
    if (wide) {
        edgeBgs = (1 << 1) | (1 << 2) | (1 << 3);
        if (Gen5MoveBgShown()) {
            edgeMirrorBgs = 1 << 3;
        }
    } else if (EncounterEffect_PortWildPlaying()) {
        // A wild battle's own transition (the black or white tiles that flip the overworld away, on BG3): its edges
        // reach the sides too, instead of a 4:3 box over the (already wide) field it covers
        wide = TRUE;
        edgeBgs = 1 << 3;
    } else if (WideApplication(&wideBgs, &edgeBgs, &isPokegear)) {
        // An app over the field whose own background reaches the edges: the Pokégear, whose gray bezel
        // (UpdatePokegearBezel) fills the gap the background doesn't cover, and the contest's swap screen
        wide = TRUE;
    } else if (fieldSystem != NULL) {
        wide = WeatherLayers(fieldSystem, &objWrap, &wideBgs);
        if (StartMenu_PortBarShown()) {
            // X's menu: its gray bar (BG3, a vertical gradient) reaches the edges, its rows continued
            edgeBgs |= 1 << 3;
        }
    }
    // The cut-ins before a Gym Leader's, Silver's, an Elite Four member's or Lance's battle (encounter_effect_leaders.c),
    // as the Platinum fork widens its own
    u8 mirrorBgs = 0;
    u8 objEdge = Gen5BattleShown() ? 0x01 : 0;
    if (!Gen5BattleShown() && EncounterEffect_PortGymLeaderPlaying()) {
        // The banner is BG3, scrolling behind the zigzag wipe's window: drawn across the sides, mirrored
        wide = TRUE;
        wideBgs |= 1 << 3;
        mirrorBgs |= 1 << 3;
    }
    if (!Gen5BattleShown() && EncounterEffect_PortEliteFourPlaying()) {
        // The band's purple slashes are sprites of priority 2 (the portraits keep 1): their edge columns continue to
        // the sides
        wide = TRUE;
        objEdge = 0x04;
    }
    UpdatePokegearBezel(isPokegear);
    SIM_SetWidescreenSceneOptions(FALSE, wideBgs);
    SIM_SetWidescreenObjWrap(objWrap);
    SIM_SetWidescreenBgMirror(mirrorBgs);
    SIM_SetWidescreenBgEdgeExtend(edgeBgs);
    SIM_SetWidescreenBgEdgeMirror(edgeMirrorBgs);
    SIM_SetWidescreenBgStripe(0, 255.0f / 256.0f);
    SIM_SetWidescreenObjEdgeExtend(objEdge);
    SIM_SetWidescreenScene(wide);
}

static float WantedRatio(const Camera *camera) {
    FieldSystem *fieldSystem = ShownFieldSystem();
    if (fieldSystem == NULL || camera != fieldSystem->camera || !SIM_IsWidescreenActive()) {
        return 1.0f;
    }
    return SIM_WidescreenRatio();
}

fx32 Widescreen_AspectRatio(const Camera *camera, fx32 aspectRatio) {
    FieldSystem *fieldSystem = FieldSystem_PortGet();
    if (fieldSystem == NULL || camera != fieldSystem->camera) {
        return aspectRatio;
    }
    const float ratio = WantedRatio(camera);
    sFieldCamera = camera;
    sFieldRatio = ratio;
    return ratio == 1.0f ? aspectRatio : (fx32)((float)aspectRatio * ratio);
}

void Widescreen_BeforeFieldRender(FieldSystem *fieldSystem) {
    Camera *camera = fieldSystem->camera;
    // Only while the field camera is the one in use: the projection is global
    if (camera == NULL || Camera_PortGetActive() != camera) {
        return;
    }
    if (sFieldCamera != camera || sFieldRatio != WantedRatio(camera)) {
        Camera_ApplyPerspectiveType(camera->perspectiveType, camera);
    }
}
